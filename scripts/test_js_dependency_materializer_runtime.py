class FakeNative:
    def __init__(self, contract: AUTH.JSDependencyMaterializationContract) -> None:
        self.contract = contract
        self.calls: list[str] = []
        self.requests: list[dict[str, object]] = []
        self.fail_operation: str | None = None
        self.crash_once: str | None = None
        self.crashed = False
        self.mutate: str | None = None

    def execute(self, _capability: object, raw: bytes) -> bytes:
        request = json.loads(raw)
        self.requests.append(request)
        operation = request["operation"]
        self.calls.append(operation)
        if self.crash_once == operation and not self.crashed:
            self.crashed = True
            first_output = Path(next(iter(request["outputs"].values())))
            first_output.mkdir(parents=True, exist_ok=True)
            (first_output / "partial").write_bytes(b"partial")
            raise RuntimeError("simulated native crash")
        if self.fail_operation == operation:
            raise RuntimeError("simulated native failure")
        outputs = {name: Path(path) for name, path in request["outputs"].items()}
        if operation == "PREPARE_TOOLCHAIN":
            node = Path(self.contract.toolchain.node_executable_path)
            yarn = Path(self.contract.toolchain.yarn_cli_path)
            node.parent.mkdir(parents=True, exist_ok=True)
            yarn.parent.mkdir(parents=True, exist_ok=True)
            node.write_bytes(b"node executable")
            yarn.write_bytes(b"yarn cli")
            node.chmod(0o500)
            yarn.chmod(0o400)
        elif operation == "ONLINE_INSTALL":
            outputs["modules"].mkdir(parents=True)
            if self.mutate != "empty-modules":
                (outputs["modules"] / "dependency").mkdir()
                (outputs["modules"] / "dependency" / "index.js").write_bytes(b"module")
                (outputs["modules"] / "dependency" / "package.json").write_bytes(
                    b'{"name":"dependency","version":"1.2.3"}\n'
                )
                (outputs["modules"] / "dev").mkdir()
                (outputs["modules"] / "dev" / "package.json").write_bytes(
                    b'{"name":"dev","version":"2.0.1"}\n'
                )
                (outputs["modules"] / ".yarn-integrity").write_bytes(
                    _canonical(
                        {
                            "lockfileEntries": {
                                "dependency@^1.0.0": "https://registry.yarnpkg.com/dependency/-/dependency-1.2.3.tgz",
                                "dev@~2.0.0": "https://registry.npmjs.org/dev/-/dev-2.0.1.tgz",
                            },
                            "topLevelPatterns": [
                                "dependency@^1.0.0",
                                "dev@~2.0.0",
                            ],
                        }
                    )
                    + b"\n"
                )
                if self.mutate == "integrity":
                    (outputs["modules"] / ".yarn-integrity").write_bytes(
                        b'{"lockfileEntries":{},"topLevelPatterns":[]}\n'
                    )
                elif self.mutate == "integrity-value":
                    integrity_path = outputs["modules"] / ".yarn-integrity"
                    integrity = json.loads(integrity_path.read_bytes())
                    integrity["lockfileEntries"]["dependency@^1.0.0"] = (
                        "https://attacker.invalid/dependency-1.2.3.tgz"
                    )
