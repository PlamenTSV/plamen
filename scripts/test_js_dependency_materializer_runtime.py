def test_native_guest_js_projection_is_one_descriptor_bound_transaction(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
) -> None:
    project = tmp_path / "projection-project"
    private = tmp_path / "projection-private"
    modules = private / "offline-modules"
    project.mkdir()
    private.mkdir()
    modules.mkdir()
    (project / "C.sol").write_text("contract C {}\n")
    (modules / "dependency").mkdir()
    receipt = {
        "schema": "plamen.js-dependency-materialization-receipt.v2",
        "receipt_sha256": "1" * 64,
    }
    dependency = RUNTIME.JSDependencyMaterializationResult(
        private_root=str(private),
        modules_root=str(modules),
        receipt_path=str(private / "materialization.receipt.json"),
        receipt_sha256="1" * 64,
        receipt=receipt,
    )
    monkeypatch.setattr(
        RUNTIME, "execute_native_guest_js_dependency_materialization",
        lambda *_args, **_kwargs: dependency,
    )
    native_authority = object()
    projection_authority = object()
    projection_receipt = _canonical({
        "schema": "plamen.private-analysis-projection-custody.v1",
    })
    lineage = _canonical({
        "schema": "plamen.evm-tool-materialization-lineage.v2",
    })
    import posix_backend_execution as runtime

    def commit(_runtime: object, **kwargs: object) -> object:
        assert _runtime is native_authority
        assert kwargs["dependency_materialization_receipt"] is receipt
        scratch_fd = int(kwargs["scratch_fd"])
        state_fd = int(kwargs["state_fd"])
        os.mkdir("analysis-workspace", 0o700, dir_fd=scratch_fd)
        descriptor = os.open(
            "materialization-lineage.json",
            os.O_WRONLY | os.O_CREAT | os.O_EXCL,
            0o400,
            dir_fd=state_fd,
        )
        try:
            os.write(descriptor, lineage)
        finally:
            os.close(descriptor)
        return projection_authority

    workspace_path = (
        private / "evm-analysis-projection" / "scratch" / "analysis-workspace"
    )
    binding = _canonical({
        "descriptor_identity_sha256": "2" * 64,
        "projection_receipt_sha256": _sha(projection_receipt),
        "schema": "plamen.evm-analysis-projection-workspace-binding.v1",
        "workspace_path": str(workspace_path),
    })
    monkeypatch.setattr(runtime, "commit_native_guest_evm_analysis_projection", commit)
    monkeypatch.setattr(
        runtime, "project_native_guest_evm_analysis_projection_receipt",
        lambda *_args: projection_receipt,
    )
    monkeypatch.setattr(
        runtime, "project_native_guest_evm_analysis_projection_lineage",
        lambda *_args: lineage,
    )
    monkeypatch.setattr(
        runtime, "project_native_guest_evm_analysis_projection_workspace_binding",
        lambda *_args: binding,
    )
    source = AUTH.ImmutableJSSourceInputs(
        source_root=str(project),
        source_snapshot_sha256="3" * 64,
        package_json=b"{}\n",
        lockfiles=(),
    )
    workspace = AUTH.PrivateDependencyWorkspaceInputs(
        private_root=str(private), generation_id="generation-1",
        phase_timeout_seconds=30, max_dependency_entries=100,
        max_dependency_expanded_bytes=1024 * 1024,
        max_cache_expanded_bytes=1024 * 1024,
    )
    result = RUNTIME.execute_native_guest_js_and_evm_analysis_projection(
        source, workspace,
        repository_root=tmp_path,
        target_os="darwin",
        target_arch="arm64",
        native_runtime_authority=native_authority,
        original_source_scope_sha256="3" * 64,
    )
    assert result.native_projection_authority is projection_authority
    assert result.workspace_binding["workspace_path"] == str(workspace_path)
    assert Path(result.projection_receipt_path).read_bytes() == projection_receipt
    assert Path(result.materialization_lineage_path).read_bytes() == lineage
    assert not (project / "node_modules").exists()
