@pytest.mark.parametrize(
    "debt_code",
    [
        "PACKAGED_ARTIFACT_MISSING",
        "PACKAGED_ARTIFACT_SIZE_MISMATCH",
        "PACKAGED_ARTIFACT_DIGEST_MISMATCH",
    ],
)
def test_missing_or_unauthenticated_yarn_bytes_have_a_typed_failure(
    monkeypatch: pytest.MonkeyPatch,
    debt_code: str,
) -> None:
    authority = TOOLCHAIN.load_authority_manifest(
        ROOT,
        bootstrap_authority=BOOTSTRAP_AUTHORITY,
    )
    node, yarn = TOOLCHAIN.select_artifacts(
        authority, os_name="darwin", arch="arm64"
    )
    debt = (
        TOOLCHAIN.PackagingDebt(
            yarn.artifact_id,
            debt_code,
            yarn.packaged_path,
        ),
    )
    monkeypatch.setattr(
        MATERIALIZER.TOOLCHAIN,
        "load_authority_manifest",
        lambda _root, *, bootstrap_authority: authority,
    )

    def unavailable(*_args: object, **_kwargs: object) -> object:
        raise TOOLCHAIN.JSToolchainPackagingError(debt)

    monkeypatch.setattr(
        MATERIALIZER.TOOLCHAIN, "require_packaged_artifacts", unavailable
    )
    with pytest.raises(MATERIALIZER.JSDependencyMaterializationError) as raised:
        MATERIALIZER.build_js_dependency_materialization_contract(
            _source(),
            _workspace(),
            bootstrap_authority=BOOTSTRAP_AUTHORITY,
            repository_root=ROOT,
            target_os="darwin",
            target_arch="arm64",
        )
    assert raised.value.code == "YARN_TOOLCHAIN_BYTES_UNAVAILABLE"
    assert raised.value.packaging_debt == debt
    assert node.artifact_id not in {item.artifact_id for item in debt}


