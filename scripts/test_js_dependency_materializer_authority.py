def test_exact_online_then_clean_offline_replay_contract(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    contract = _build(monkeypatch)

    assert contract.source_access == "IMMUTABLE_READ_ONLY_SNAPSHOT"
    assert contract.workspace_access == "PRIVATE_EMPTY_OUT_OF_TREE"
    assert contract.execution_state == "PLAN_ONLY_NATIVE_LIFECYCLE_REQUIRED"
    assert contract.lock_selection.family == "yarn"
    authority = TOOLCHAIN.load_authority_manifest(
        ROOT,
        bootstrap_authority=BOOTSTRAP_AUTHORITY,
    )
    yarn = authority.artifacts[-1]
    assert contract.toolchain.yarn_archive_sha256 == yarn.sha256
    assert contract.toolchain.yarn_archive_size == yarn.size
    assert contract.toolchain.upstream_verification_sha256 == (
        authority.upstream_verification_sha256
    )
    assert contract.online.cwd == contract.offline_replay.cwd == "/audit/source"
    assert contract.online.modules_root == (
        "/private/dependencies/scratch/online/modules"
    )
    assert contract.offline_replay.modules_root == (
        "/private/dependencies/scratch/offline-replay/modules"
    )
    assert contract.online.cache_root != contract.offline_replay.cache_root
    assert contract.replay.online_cache_root == contract.online.cache_root
    assert contract.replay.offline_cache_seed_root == (
        contract.offline_replay.cache_root
    )
    assert contract.replay.cache_handoff == (
        "COPY_VERIFIED_TREE_INTO_EMPTY_OFFLINE_CACHE"
    )
    assert ("cache_tree_sha256", "seed_cache_tree_sha256") in (
        contract.replay.required_receipt_equalities
    )
    assert "OFFLINE_NETWORK_DENIAL_REMAINED_ACTIVE" in (
        contract.replay.required_terminal_conditions
    )
    assert contract.online.network_mode == (
        "VERIFIED_EXACT_LOCK_ORIGIN_ALLOWLIST"
    )
    assert contract.online.egress_target_id == "yarn-classic-registry"
    assert contract.offline_replay.network_mode == "NO_NETWORK"
    assert contract.offline_replay.egress_target_id == ""
    assert contract.online.argv[-2:] == (
        "--registry",
        "https://registry.yarnpkg.com",
    )
    assert contract.offline_replay.argv[-1] == "--offline"
    assert "--ignore-scripts" in contract.online.argv
    assert "--frozen-lockfile" in contract.online.argv
    toolchain_binding = contract.toolchain.binding_dict()
    binding_sha256 = toolchain_binding.pop("binding_sha256")
    assert binding_sha256 == hashlib.sha256(
        json.dumps(
            toolchain_binding,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=True,
            allow_nan=False,
        ).encode("ascii")
    ).hexdigest()
    assert contract.contract_sha256 == hashlib.sha256(
        json.dumps(
            contract.binding_dict(),
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=True,
            allow_nan=False,
        ).encode("ascii")
    ).hexdigest()


