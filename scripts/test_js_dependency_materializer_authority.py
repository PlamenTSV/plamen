@pytest.fixture(scope="session")
def _rendered_runtime_closure(
    tmp_path_factory: pytest.TempPathFactory,
) -> Path:
    closure = (
        tmp_path_factory.mktemp("js-materializer-closure")
        / "toolchain_runtime_closure.v1.json"
    )
    member_paths = {
        "scripts/js_dependency_materializer_authority.py",
        "scripts/js_dependency_materializer_runtime.py",
        "scripts/js_lock_authority.py",
        "scripts/js_toolchain_authority.py",
        TOOLCHAIN.BOOTSTRAP_RELATIVE_PATH.as_posix(),
        TOOLCHAIN.MANIFEST_RELATIVE_PATH.as_posix(),
    }
    policy = json.loads(
        (ROOT / TOOLCHAIN.MANIFEST_RELATIVE_PATH).read_text(encoding="utf-8")
    )
    member_paths.update(row["packaged_path"] for row in policy["artifacts"])
    assets = []
    for relative in sorted(member_paths):
        raw = (ROOT / relative).read_bytes()
        if relative.endswith(".py"):
            kind = "python-source"
            digest_mode = "utf8-lf-v1"
            canonical = raw.decode("utf-8").replace("\r\n", "\n").encode()
        elif relative.startswith("verification_policy/"):
            kind = "control"
            digest_mode = "utf8-lf-v1"
            canonical = raw.decode("utf-8").replace("\r\n", "\n").encode()
        else:
            kind = "runtime-data"
            digest_mode = "raw-v1"
            canonical = raw
        assets.append(
            {
                "digest_mode": digest_mode,
                "kind": kind,
                "path": relative,
                "sha256": hashlib.sha256(canonical).hexdigest(),
            }
        )
    closure_relative = TOOLCHAIN.RUNTIME_CLOSURE_RELATIVE_PATH.as_posix()
    payload = {
        "assets": assets,
        "derivation": "python-ast-typed-runtime-closure-v2",
        "entrypoints": ["scripts/js_toolchain_authority.py"],
        "files": sorted({*member_paths, closure_relative}),
        "manifest_control": {
            "kind": "control",
            "path": closure_relative,
        },
        "schema": TOOLCHAIN.RUNTIME_CLOSURE_SCHEMA,
    }
    closure.write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n",
        encoding="ascii",
        newline="\n",
    )
    return closure


