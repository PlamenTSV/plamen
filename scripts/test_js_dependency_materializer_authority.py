def test_declared_npm_never_falls_through_to_yarn_materializer(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    called = False

    def load(
        _root: object,
        *,
        bootstrap_authority: TOOLCHAIN.TrustedJSBootstrapAuthority,
    ) -> object:
        nonlocal called
        called = True
        raise AssertionError("toolchain must not be inspected")

    monkeypatch.setattr(MATERIALIZER.TOOLCHAIN, "load_authority_manifest", load)
    with pytest.raises(MATERIALIZER.JSDependencyMaterializationError) as raised:
        MATERIALIZER.build_js_dependency_materialization_contract(
            _source(locks=(("package-lock.json", _npm()),), manager="npm@10.0.0"),
            _workspace(),
            bootstrap_authority=BOOTSTRAP_AUTHORITY,
            repository_root=ROOT,
            target_os="darwin",
            target_arch="arm64",
        )
    assert raised.value.code == "JS_LOCK_FAMILY_NOT_IMPLEMENTED"
    assert called is False


