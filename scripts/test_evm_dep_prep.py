def test_projection_build_root_does_not_redefine_original_source_scope(tmp_path):
    rp = _rp()
    root = tmp_path / "project"
    projection = tmp_path / "projection"
    scratch = tmp_path / "scratch"
    scratch.mkdir()
    _mk(root / "foundry.toml", "[profile.default]\nlibs=['lib']\n")
    _mk(root / "contracts" / "Vault.sol", "contract Vault {}\n")
    _mk(root / "lib" / "dep" / "Dep.sol", "library Dep {}\n")
    _mk(projection / "foundry.toml", "[profile.default]\nlibs=['lib']\n")
    _mk(projection / "contracts" / "Vault.sol", "contract Vault { uint x; }\n")
    _mk(projection / "lib" / "dep" / "Dep.sol", "library Dep { uint x; }\n")
    config = {
        "project_root": str(root),
        "scratchpad": str(scratch),
        "pipeline": "sc",
        "language": "evm",
    }
    rp.resolve_snapshot_build_root(config)
    before = rp._audit_snapshot_authority._source_component(config)

    config["_resolved_build_root"] = str(projection)
    after = rp._audit_snapshot_authority._source_component(config)

    assert after["digest"] == before["digest"]


