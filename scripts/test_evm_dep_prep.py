def test_native_projection_binds_opaque_authority_and_staging_paths(
    tmp_path, monkeypatch,
):
    rp = _rp()
    import evm_analysis_workspace_authority as workspace_authority
    import js_dependency_materializer_runtime as runtime

    project = tmp_path / "project"
    scratch = tmp_path / "scratch"
    scratch.mkdir(mode=0o700)
    _reviewed_yarn_inputs(project)
    _mk(project / "contracts" / "Vault.sol", "contract Vault {}\n")
    run_id = "run-123"
    private = (
        scratch / ".evm-analysis-projection-staging"
        / f"js-materialization-{run_id}"
    )
    projection = private / "evm-analysis-projection"
    receipt = projection / "state" / "projection-receipt.json"
    lineage = projection / "state" / "materialization-lineage.json"
    workspace = projection / "scratch" / "analysis-workspace"
    native = object()
    projection_authority = object()
    observed = {}

    def execute(source, private_inputs, **kwargs):
        observed.update(source=source, workspace=private_inputs, kwargs=kwargs)
        return types.SimpleNamespace(
            workspace_binding={"workspace_path": str(workspace)},
            projection_receipt_path=str(receipt),
            materialization_lineage_path=str(lineage),
            native_projection_authority=projection_authority,
        )

    monkeypatch.setattr(
        rp._audit_snapshot_authority,
        "_source_component",
        lambda _config: {"digest": "3" * 64},
    )
    monkeypatch.setattr(
        runtime, "execute_native_guest_js_and_evm_analysis_projection", execute
    )
    config = {
        "_run_id": run_id,
        "project_root": str(project),
        "scratchpad": str(scratch),
        "pipeline": "sc",
        "language": "evm",
    }

    note = rp._prepare_native_js_evm_projection(
        config, project.resolve(), native_runtime_authority=native
    )

    assert "authenticated native Yarn" in note
    assert observed["source"].source_snapshot_sha256 == "3" * 64
    assert dict(observed["source"].lockfiles).keys() == {"yarn.lock"}
    assert observed["workspace"].private_root == str(private)
    assert observed["kwargs"]["native_runtime_authority"] is native
    assert observed["kwargs"]["original_source_scope_sha256"] == "3" * 64
    assert config["_resolved_build_root"] == str(workspace)
    assert config[
        workspace_authority.ANALYSIS_PROJECTION_NATIVE_AUTHORITY_CONFIG
    ] is projection_authority
    assert config[
        workspace_authority.ANALYSIS_PROJECTION_STAGING_RECEIPT_CONFIG
    ] == str(receipt)
    assert config[
        workspace_authority.MATERIALIZATION_LINEAGE_STAGING_CONFIG
    ] == str(lineage)


