"""P3 — EVM input preparation and FOUNDRY_PROFILE resolution.

Unreviewed Forge/Soldeer materialization stays unavailable before native
authority.  A legacy direct JavaScript lane may execute only the unique exact
manifest-consistent lock selected by the shared lock authority.
"""
from __future__ import annotations

import importlib
import base64
import hashlib
import os
import sys
import types
from pathlib import Path
from unittest import mock


def _rp():
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    return importlib.import_module("recon_prepass")


def _mk(p: Path, body: str = "x"):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(body, encoding="utf-8")


def _reviewed_yarn_inputs(root: Path) -> None:
    _mk(
        root / "package.json",
        '{"dependencies":{"dependency":"^1.0.0"},"name":"fixture","version":"1.0.0"}\n',
    )
    integrity = "sha512-" + base64.b64encode(
        hashlib.sha512(b"dependency").digest()
    ).decode("ascii")
    _mk(
        root / "yarn.lock",
        "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n"
        "# yarn lockfile v1\n\n"
        '"dependency@^1.0.0":\n'
        '  version "1.2.3"\n'
        '  resolved "https://registry.yarnpkg.com/dependency/-/dependency-1.2.3.tgz"\n'
        f"  integrity {integrity}\n",
    )


