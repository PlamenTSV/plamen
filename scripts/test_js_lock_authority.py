    root = Path.home() / "dodo-cross-chain-dex" / "omni-chain-contracts"
    required = [root / "package.json", root / "package-lock.json", root / "yarn.lock"]
    if not all(path.is_file() for path in required):
        pytest.skip("DODO exact-file fixture is not present in this workspace")

    package = required[0].read_bytes()
    npm_lock = required[1].read_bytes()
    yarn_lock = required[2].read_bytes()
    assert hashlib.sha256(package).hexdigest() == (
        "2b061d9012f97f7d6b56ccb40236dc99eee8a85bce01671028a35a08d2c63b0f"
    )
