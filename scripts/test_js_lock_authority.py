def test_unused_stanza_is_bound_but_is_not_selection_evidence() -> None:
    package = _package({"a": "^1"})
    first = select_js_lock_authority(
        package,
        {
            "yarn.lock": _yarn(
                _entry("a@^1"),
                _entry(
                    "unused@^7",
                    version="7.0.0",
                    resolved="http://unused.invalid/not-fetched.tgz",
                    integrity="sha1-AAAAAAAAAAAAAAAAAAAAAAAAAAA=",
                ),
            )
        },
    )
    second = select_js_lock_authority(
        package,
        {
            "yarn.lock": _yarn(
                _entry("a@^1"),
                _entry(
                    "unused@^8",
                    version="8.0.0",
                    resolved="http://unused.invalid/still-not-fetched.tgz",
                    integrity="sha1-AAAAAAAAAAAAAAAAAAAAAAAAAAA=",
                ),
            )
        },
    )

    assert first.family == second.family == "yarn"
    assert first.reachable_selectors_sha256 == second.reachable_selectors_sha256
    assert first.unused_stanza_count == second.unused_stanza_count == 1
    assert first.unused_selectors_sha256 != second.unused_selectors_sha256
    assert first.lockfile_sha256 != second.lockfile_sha256
    assert first.selection_sha256 != second.selection_sha256


