def test_yarn_recursive_graph_and_grouped_selectors_select() -> None:
    package = _package({"a": "^1"})
    lock = _yarn(
        _entry("a@^1", dependencies={"b": "~2.0.0"}),
        _entry(("b@~2.0.0", "b@^2"), version="2.1.0"),
    )

    selected = select_js_lock_authority(package, {"yarn.lock": lock})

    assert selected.family == "yarn"
    assert selected.selection_basis == UNIQUE_MANIFEST_CONSISTENT_LOCK
    assert selected.reachable_stanza_count == 2
    assert selected.unused_stanza_count == 0

    integrity = derive_yarn_integrity_authority(package, lock, selected)
    assert integrity.lockfile_entries == (
        ("a@^1", "https://registry.example.invalid/a-^1.tgz"),
        ("b@^2", "https://registry.example.invalid/b-~2.0.0.tgz"),
        ("b@~2.0.0", "https://registry.example.invalid/b-~2.0.0.tgz"),
    )
    assert integrity.direct_packages == (("a", "a@^1", "1.0.0"),)


def test_yarn_integrity_authority_binds_resolved_values_not_only_keys() -> None:
    package = _package({"a": "^1"})
    first_lock = _yarn(_entry("a@^1"))
    second_lock = _yarn(
        _entry(
            "a@^1",
            resolved="https://registry.yarnpkg.com/a/-/alternate-a-1.0.0.tgz",
        )
    )
    first_selection = select_js_lock_authority(package, {"yarn.lock": first_lock})
    second_selection = select_js_lock_authority(package, {"yarn.lock": second_lock})
    first = derive_yarn_integrity_authority(package, first_lock, first_selection)
    second = derive_yarn_integrity_authority(package, second_lock, second_selection)
    assert first.lockfile_entries[0][0] == second.lockfile_entries[0][0]
    assert first.lockfile_entries[0][1] != second.lockfile_entries[0][1]
    assert first.lockfile_entries_sha256 != second.lockfile_entries_sha256
    assert first.authority_sha256 != second.authority_sha256


