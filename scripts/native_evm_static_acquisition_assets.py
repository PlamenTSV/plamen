def _fail(message: str) -> NoReturn:
    raise NativeEVMStaticAcquisitionError(message) from None


def _pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if type(key) is not str or key in result:
            _fail("acquisition JSON contains a duplicate/non-string key")
        result[key] = value
    return result


def _canonical(value: Any, *, final_lf: bool) -> bytes:
    try:
        raw = json.dumps(
            value, sort_keys=True, separators=(",", ":"), ensure_ascii=True,
            allow_nan=False,
        ).encode("ascii")
    except (TypeError, ValueError, UnicodeError):
        _fail("acquisition JSON is not canonicalizable")
    return raw + (b"\n" if final_lf else b"")


def _decode_exact(
    raw: bytes, *, digest: str, size: int, label: str, final_lf: bool,
    canonical: bool = True,
) -> dict[str, Any]:
    if (
        type(raw) is not bytes or len(raw) != size
        or _HEX64.fullmatch(digest) is None
        or hashlib.sha256(raw).hexdigest() != digest
    ):
        _fail(f"{label} exact bytes differ")
    try:
        value = json.loads(
            raw.decode("ascii", "strict"), object_pairs_hook=_pairs,
            parse_constant=lambda token: _fail(f"{label} contains {token}"),
        )
    except (UnicodeError, json.JSONDecodeError):
        _fail(f"{label} is not strict JSON")
    if type(value) is not dict or (
        canonical and raw != _canonical(value, final_lf=final_lf)
    ):
        _fail(f"{label} is not canonical JSON")
    return value


def _contract(role: str) -> RoleContract:
    if type(role) is not str or role not in CONTRACTS:
        _fail("EVM static acquisition role is unsupported")
    return CONTRACTS[role]


def load_reviewed_policy(
    role: str, policy_raw: bytes, *, managed_evm_policy_raw: bytes | None = None,
) -> dict[str, Any]:
    """Validate exact reviewed policy bytes without conferring authority."""

    contract = _contract(role)
    if role == "medusa":
        try:
            value = medusa.load_medusa_acquisition_policy(policy_raw)
        except medusa.MedusaReleasePolicyError as exc:
            raise NativeEVMStaticAcquisitionError(str(exc)) from None
        if len(policy_raw) != contract.policy_size:
            _fail("medusa policy exact bytes differ")
        return value
    value = _decode_exact(
        policy_raw, digest=SOLC_POLICY_SHA256, size=SOLC_POLICY_SIZE,
        label="solc-amd64 policy", final_lf=True,
    )
    if frozenset(value) != {
        "artifact", "materialization", "reviewed_source", "schema"
    } or value.get("schema") != "plamen.solc-amd64-acquisition-policy.v1":
        _fail("solc-amd64 policy field set or schema differs")
    artifact = value.get("artifact")
    materialization = value.get("materialization")
    reviewed = value.get("reviewed_source")
    if (
        type(artifact) is not dict or artifact != _solc_artifact()
        or materialization != {
            "acquisition_scope": "SETUP_ONLY",
            "ambient_solc_select": "DENY", "audit_network": "DENY",
            "identity_mode": "STATIC_PAYLOAD",
            "next_required_authority": NEXT_REQUIRED_AUTHORITY,
            "rosetta_required": True,
        }
        or reviewed != {
            "path": MANAGED_EVM_POLICY_PATH,
            "schema": "plamen.managed-evm-python-toolchain-policy.v1",
            "sha256": MANAGED_EVM_POLICY_SHA256,
            "size": MANAGED_EVM_POLICY_SIZE,
            "target_id": "linux-x86_64",
        }
    ):
        _fail("solc-amd64 reviewed policy semantics differ")
    if managed_evm_policy_raw is None:
        _fail("managed-EVM parent policy bytes are required")
    parent = _decode_exact(
        managed_evm_policy_raw, digest=MANAGED_EVM_POLICY_SHA256,
        size=MANAGED_EVM_POLICY_SIZE, label="managed-EVM parent policy",
        final_lf=True, canonical=False,
    )
    targets = parent.get("targets")
    matches = [row for row in targets if type(row) is dict and row.get("id") == "linux-x86_64"] if type(targets) is list else []
    if (
        parent.get("schema") != reviewed["schema"] or len(matches) != 1
        or matches[0].get("machine") != "x86_64"
        or matches[0].get("sys_platform") != "linux"
        or matches[0].get("status") != "SUPPORTED"
        or matches[0].get("compiler") != _managed_solc_compiler()
    ):
        _fail("solc-amd64 parent policy projection differs")
    return value


