def _source_manifest(contract: RoleContract) -> bytes:
    return _canonical({
        "artifact_id": contract.artifact_id,
        "authentication_scope": AUTHENTICATION_SCOPE,
        "media_type": "application/vnd.plamen.executable",
        "payload_sha256": contract.payload_sha256,
        "payload_size": contract.payload_size,
        "platform": contract.platform,
        "required_paths": [contract.install_path], "role": contract.role,
        "schema_version": SOURCE_MANIFEST_SCHEMA,
        "source_reference": contract.source_reference,
        "version": contract.version,
    }, final_lf=True)


def _semantic_receipt(contract: RoleContract) -> bytes:
    manifest = _source_manifest(contract)
    common: dict[str, Any] = {
        "artifact_id": contract.artifact_id,
        "generation": {"renderer": RENDERER_PATH, "schema": RENDERER_SCHEMA},
        "payload": {"sha256": contract.payload_sha256, "size": contract.payload_size},
        "platform": contract.platform, "policy_sha256": contract.policy_sha256,
        "role": contract.role, "schema": contract.receipt_schema,
        "source_manifest": {
            "sha256": hashlib.sha256(manifest).hexdigest(), "size": len(manifest),
        },
        "version": contract.version,
    }
    if contract.role == "medusa":
        common["authentication"] = {
            "archive": {"sha256": medusa.ARCHIVE_SHA256, "size": medusa.ARCHIVE_SIZE},
            "certificate_identity": medusa.CERTIFICATE_IDENTITY,
            "certificate_oidc_issuer": medusa.CERTIFICATE_OIDC_ISSUER,
            "sigstore_bundle": {
                "sha256": medusa.SIGSTORE_BUNDLE_SHA256,
                "size": medusa.SIGSTORE_BUNDLE_SIZE,
            },
            "source_commit": medusa.SOURCE_COMMIT,
        }
        common["materialization"] = {
            "archive_format": "tar.gz", "archive_member": "medusa",
            "destination": contract.install_path, "mode": "0555",
            "projection": "EXACT_SOLE_REGULAR_MEMBER_V1",
        }
    else:
        artifact = _solc_artifact()
        common["authentication"] = {
            "provider_index": {
                "sha256": artifact["provider_index"]["sha256"],
                "size": artifact["provider_index"]["size"],
            },
            "reviewed_parent_policy": {
                "sha256": MANAGED_EVM_POLICY_SHA256, "size": MANAGED_EVM_POLICY_SIZE,
            },
        }
        common["selection"] = {
            "build": "commit.8a97fa7a",
            "keccak256": artifact["binary"]["keccak256"],
            "long_version": contract.version,
            "path": artifact["provider_index"]["selected_path"],
            "release_key": artifact["provider_index"]["release_key"],
            "sha256": contract.payload_sha256, "version": "0.8.26",
        }
        common["materialization"] = {
            "destination": contract.install_path, "mode": "0555",
            "projection": "EXACT_PROVIDER_SELECTED_EXECUTABLE_V1",
        }
    return _canonical(common, final_lf=False)


def render_assets(
    role: str, policy_raw: bytes, *, managed_evm_policy_raw: bytes | None = None,
) -> tuple[bytes, bytes]:
    """Return ``(semantic receipt prefix, source manifest)`` exact bytes."""

    contract = _contract(role)
    load_reviewed_policy(
        role, policy_raw, managed_evm_policy_raw=managed_evm_policy_raw,
    )
    receipt, manifest = _semantic_receipt(contract), _source_manifest(contract)
    _require_render_freeze(contract, receipt, manifest)
    return receipt, manifest


def _require_render_freeze(
    contract: RoleContract, receipt: bytes, manifest: bytes,
) -> None:
    if (
        len(receipt) != contract.receipt_size
        or hashlib.sha256(receipt).hexdigest() != contract.receipt_sha256
        or len(manifest) != contract.source_manifest_size
        or hashlib.sha256(manifest).hexdigest()
        != contract.source_manifest_sha256
    ):
        _fail(f"{contract.role} renderer output differs from the reviewed freeze")


def validate_semantic_receipt(role: str, raw: bytes) -> dict[str, Any]:
    contract = _contract(role)
    expected = _semantic_receipt(contract)
    return _decode_exact(
        raw, digest=contract.receipt_sha256, size=contract.receipt_size,
        label=f"{role} semantic receipt", final_lf=False,
    )


def validate_source_manifest(role: str, raw: bytes) -> dict[str, Any]:
    contract = _contract(role)
    expected = _source_manifest(contract)
    return _decode_exact(
        raw, digest=contract.source_manifest_sha256,
        size=contract.source_manifest_size,
        label=f"{role} source manifest", final_lf=True,
    )


def native_operation4_evm_policy_input(role: str) -> dict[str, Any]:
    """Project an exact compile-time row; never issue production authority."""

    contract = _contract(role)
    receipt, manifest = _semantic_receipt(contract), _source_manifest(contract)
    _require_render_freeze(contract, receipt, manifest)
    return {
        "identity_mode": STATIC_PAYLOAD_IDENTITY_MODE,
        "payload_sha256": contract.payload_sha256,
        "payload_size": contract.payload_size,
        "policy_sha256": contract.policy_sha256,
        "producer_fd_size": contract.receipt_size + PRODUCER_FOOTER_SIZE,
        "receipt_schema": contract.receipt_schema,
        "receipt_validator": contract.receipt_validator,
        "role": contract.role, "role_ordinal": contract.ordinal,
        "semantic_receipt_sha256": contract.receipt_sha256,
        "semantic_receipt_size": contract.receipt_size,
        "source_manifest_sha256": contract.source_manifest_sha256,
        "source_manifest_size": contract.source_manifest_size,
        "version": contract.version,
    }


def native_coordinator_evm_acquisition_input(role: str) -> dict[str, Any]:
    """Describe the retained native producer ABI without exposing/issuing FDs."""

    contract = _contract(role)
    inputs = (
        (
            {"kind": "medusa_release_archive", "sha256": medusa.ARCHIVE_SHA256,
             "size": medusa.ARCHIVE_SIZE},
            {"kind": "medusa_sigstore_bundle", "sha256": medusa.SIGSTORE_BUNDLE_SHA256,
             "size": medusa.SIGSTORE_BUNDLE_SIZE},
        ) if role == "medusa" else (
            {"kind": "solc_provider_index", "sha256": _solc_artifact()["provider_index"]["sha256"],
             "size": _solc_artifact()["provider_index"]["size"]},
            {"kind": "solc_selected_binary", "sha256": contract.payload_sha256,
             "size": contract.payload_size},
        )
    )
    return {
        "next_required_authority": NEXT_REQUIRED_AUTHORITY,
        "ordered_retained_inputs": inputs,
        "policy_row": native_operation4_evm_policy_input(role),
        "producer_output": {
            "footer_size": PRODUCER_FOOTER_SIZE,
            "semantic_prefix_path": contract.receipt_path,
            "source_manifest_path": contract.source_manifest_path,
            "wire": "CANONICAL_SEMANTIC_PREFIX_NO_LF_THEN_NATIVE_FOOTER_V1",
        },
        "production_authority": False,
        "required_native_replay": (
            "SIGSTORE_BUNDLE_AND_SOLE_ARCHIVE_MEMBER_V1" if role == "medusa"
            else "SOLC_PROVIDER_INDEX_SELECTION_AND_BINARY_V1"
        ),
        "role": role,
    }


def _main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("kind", choices=("receipt", "source-manifest"))
    parser.add_argument("role", choices=tuple(CONTRACTS))
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args(argv)
    policy = (args.root / _contract(args.role).policy_path).read_bytes()
    parent = None
    if args.role == "solc_amd64":
        parent = (args.root / MANAGED_EVM_POLICY_PATH).read_bytes()
    receipt, manifest = render_assets(
        args.role, policy, managed_evm_policy_raw=parent,
    )
    sys.stdout.buffer.write(receipt if args.kind == "receipt" else manifest)
    return 0


if __name__ == "__main__":
    raise SystemExit(_main(sys.argv[1:]))


